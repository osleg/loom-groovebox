"""Pack the FM-1 variant's cached Speak37 words, without firmware or song data."""
import math
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

DONOR = "81fa061b40e6b6305e3672c671ead2552c9b8569"


def glottal(n=256, open_q=0.42, close_q=0.16):
    """Speak37's glottal flow derivative using the Python standard library."""
    opened, closed = n * open_q, n * close_q
    g = [
        0.5 * (1 - math.cos(math.pi * i / opened)) if i < opened
        else math.cos(0.5 * math.pi * (i - opened) / closed) if i < opened + closed
        else 0
        for i in range(n)
    ]
    d = [g[(i + 1) % n] - g[i] for i in range(n)]
    mean = sum(d) / n
    d = [value - mean for value in d]
    gain = 8192 / math.sqrt(sum(value * value for value in d) / n)
    return [round(gain * value) for value in d]


def make(checkout):
    revision = subprocess.check_output(["git", "-C", checkout, "rev-parse", "HEAD"], text=True).strip()
    if revision != DONOR:
        raise SystemExit("Speak37 checkout revision mismatch")
    script = checkout / "tools" / "gen_vocab.py"
    source = script.read_text()
    source = source.replace("import numpy as np", "")
    source = source.replace("    y = np.array(out)\n    return y", "    return out")
    source = source.replace("float(np.max(np.abs(decode(frames))))", "max(map(abs, decode(frames)), default=0.0)")
    source = source.replace('    CACHE.write_text(json.dumps(cache, indent=0, sort_keys=True) + "\\n")', "")
    old_dict = os.environ.get("SP_NDICT")
    argv = sys.argv
    try:
        with tempfile.TemporaryDirectory() as work:
            out = Path(work) / "donor-vocabulary.h"
            os.environ["SP_NDICT"] = "572 528"
            sys.argv = [str(script), str(out)]
            scope = {"__file__": str(script), "__name__": "speak37_vocab"}
            exec(compile(source, str(script), "exec"), scope)
            scope["glottal"] = glottal
            if scope["main"]():
                raise SystemExit("Speak37 vocabulary encoding failed")
            raw = out.read_text()
    finally:
        sys.argv = argv
        if old_dict is None:
            os.environ.pop("SP_NDICT", None)
        else:
            os.environ["SP_NDICT"] = old_dict
    count = re.search(r"#define SP_NWORD (\d+)u", raw)[1]
    byte_count = re.search(r"#define SP_LPC_BYTES (\d+)u", raw)[1]
    body = raw[raw.index("static const uint8_t SP_LPC[]"): raw.index("/* the kit (KIT mode:")]
    body = body.replace("sp_word_t", "speak37_word_t").replace("SP_WNAME", "SPEAK37_WORDS").replace("SP_NWORD", "SPEAK37_WORD_COUNT")
    lines = [
        "/* Generated by generate_vocabulary.py from Speak37 by M. Geisler.",
        " * LPC frames GPL-3.0-only. MAME coding tables and chirp BSD-3-Clause.",
        " * Editor lexicon entries include FrequencyWords CC BY-SA 4.0 data. */",
        f"#define SPEAK37_WORD_COUNT {count}u",
        f"#define SPEAK37_LPC_BYTES {byte_count}u",
        "#define SPEAK37_WORD_PERC 1u",
        "#define SPEAK37_WORD_SING 2u",
        body,
    ]
    banks = (int(count) + 63) // 64
    lines.append("static const char *const SPEAK37_BANKS[] = {")
    for bank in range(banks):
        lines.append(f'    "{bank + 1:02}",')
    lines.extend(["};", "static const param_desc_t SPEAK37_WORD_DESC[] = {"])
    for bank in range(banks):
        offset = min(bank * 64, int(count) - 64)
        lines.append(f'    {{"WORD", SPEAK37_WORDS + {offset}u, 0, 63, 0, F_ENUM, 0}},')
    lines.extend(["};", ""])
    target = Path(__file__).parent / "thirdparty" / "sp_vocabulary.h"
    target.write_text("\n".join(lines))
    print(f"Speak37 Instrument vocabulary: {count} words, {byte_count} LPC bytes")


if __name__ == "__main__":
    make(Path(sys.argv[1]).resolve())
